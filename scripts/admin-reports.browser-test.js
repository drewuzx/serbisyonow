'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const os=require('node:os');
const {randomUUID}=require('node:crypto');
const {chromium}=require('playwright');
const {startQrFixture}=require('./provider-qr-test-fixture');
const {issueSession}=require('./account-sessions');

async function main() {
 const f=await startQrFixture(); let browser;
 try {
  const admin=(await f.db.query("INSERT INTO admins(username,password_hash) VALUES('report-admin','fixture') RETURNING id,username")).rows[0];
  admin.auth_token=await issueSession(f.db,'admin',admin.id);
  const read=(query='')=>f.request('/api/admin/reports'+query,'GET',undefined,admin.auth_token);
  assert.equal((await f.request('/api/admin/reports','GET',undefined,null)).status,401);
  assert.equal((await f.request('/api/admin/reports','GET',undefined,f.customerToken)).status,403);
  assert.equal((await f.request('/api/admin/reports','GET',undefined,f.providerToken)).status,403);
  for(const query of ['?days=0','?days=31','?sort=invalid','?days[]=7']) assert.equal((await read(query)).status,400);
  const empty=await read();
  assert.equal(empty.status,200,JSON.stringify(empty.data));
  assert.equal(empty.data.bookings.total,0);
  assert.equal(empty.data.revenue.total_centavos,0);
  assert.equal(empty.data.reviews.average,null);
  assert.equal(empty.data.trend.length,30);
  assert.match(empty.headers.get('cache-control'),/no-store/);
  assert.equal(empty.data.userSummary,undefined);
  await f.db.query("UPDATE providers SET full_name=CASE id WHEN 81 THEN 'Ana Cruz' ELSE 'Marco Santos' END,category=CASE id WHEN 81 THEN 'Cleaning Services' ELSE '' END");
  await f.db.query("INSERT INTO provider_services(provider_id,title,category) VALUES(81,'Pipe repair','Home Repair')");
  await f.createBooking({status:'completed',service_details:{category:'Cleaning'}});
  await f.createBooking({status:'completed',service_details:{category:'Cleaning Services'}});
  await f.createBooking({status:'ongoing',service:'Pipe repair'});
  await f.createBooking({status:'cancelled',service_details:{category:'Cancelled category'}});
  await f.createBooking({provider_id:82,status:'completed',service_details:{category:'Repair Services'}});
  await f.createBooking({provider_id:82,status:'pending',service:'Uncategorized service'});
  await f.createBooking({created_at:new Date(new Date(empty.data.period.start).getTime()-1000),status:'completed'});
  await f.createBooking({created_at:empty.data.period.finish,status:'completed'});
  await f.db.query("INSERT INTO customer_reviews(customer_id,provider_id,rating) VALUES(61,81,5),(62,81,3),(61,82,5)");
  await f.db.query("INSERT INTO customer_reviews(customer_id,provider_id,rating,created_at) VALUES(61,82,1,$1)",[empty.data.period.previous_start]);
  const plan=(await f.db.query('SELECT id FROM promotion_plans LIMIT 1')).rows[0].id;
  const order=async(status,amount,when,name='14-day Profile Boost')=>f.db.query(`INSERT INTO promotion_orders(provider_id,plan_id,request_id,plan_name,description,duration_days,amount_centavos,status,wallet,account_name,account_number,qr_content,qr_mime,paid_at)
   VALUES(81,$1,$2,$3,'Fixture',14,$4,$5,'GCash','Fixture','test',$6,'image/png',$7)`,[plan,randomUUID(),name,amount,status,f.image,when]);
  await order('paid',10000,new Date());
  await order('paid',20000,new Date(),'Professional Subscription');
  await order('awaiting_verification',50000,null);
  await order('paid',10000,empty.data.period.previous_start);
  await order('paid',99000,empty.data.period.finish);
  const report=(await read()).data;
  assert.deepEqual(report.bookings,{total:6,previous_total:1,completed:3,cancelled:1,active:2});
  assert.deepEqual(report.revenue,{total_centavos:30000,previous_centavos:10000,payments:2});
  assert.equal(report.reviews.count,3);
  assert.equal(report.reviews.average,13/3);
  assert.deepEqual(report.categories,[{name:'Cleaning',bookings:2},{name:'Repair Services',bookings:2},{name:'Uncategorized',bookings:1}]);
  assert.equal(report.providers[0].id,81);
  assert.equal(report.providers[0].bookings,3);
  assert.equal(report.providers[0].rating,4);
  assert.equal((await read('?sort=rating')).data.providers[0].id,82);
  assert.equal(report.trend.reduce((sum,r)=>sum+r.bookings,0),6);
  assert.equal(report.trend.reduce((sum,r)=>sum+r.revenue_centavos,0),30000);
  assert.equal(report.plans.length,2);
  for(const days of [7,90,365]) assert.equal((await read(`?days=${days}`)).data.trend.length,days);

  browser=await chromium.launch({headless:true,channel:'msedge'});
  const context=await browser.newContext({viewport:{width:1440,height:1000},serviceWorkers:'block'});
  await context.route('**/*',route=>new URL(route.request().url()).origin===f.base?route.continue():route.fulfill({body:'',contentType:'text/css'}));
  await context.addInitScript(admin=>localStorage.setItem('sn_admin_user',JSON.stringify(admin)),admin);
  const page=await context.newPage(),errors=[]; page.on('pageerror',error=>errors.push(error.message));
  await page.goto(f.base+'/pages/admin/reports/reports.html');
  await page.locator('#report-content').waitFor({state:'visible'});
  assert.equal(await page.getByText('User Summary',{exact:true}).count(),0);
  assert.match(await page.locator('#report-metrics').innerText(),/50%/);
  assert.equal(await page.locator('#booking-chart button').count(),30);
  await page.locator('#booking-chart button').last().focus();
  assert.match(await page.locator('#booking-detail').innerText(),/6 bookings, 3 completed/);
  await page.locator('#revenue-chart button').last().click();
  assert.match(await page.locator('#revenue-detail').innerText(),/300/);
  const downloadEvent=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export Report',exact:true}).click();
  const download=await downloadEvent,csv=await fs.readFile(await download.path(),'utf8');
  assert.match(csv,/"Verified system earnings \(PHP\)","300.00"/);
  assert.match(csv,/"Cleaning","2"/);
  await page.getByLabel('Rank by',{exact:true}).selectOption('rating');
  await page.waitForFunction(()=>document.querySelector('#top-providers tr')?.textContent.includes('Marco Santos'));
  for(const days of ['7','90','365','30']) {
   await page.getByLabel('Period',{exact:true}).selectOption(days);
   await page.locator('#report-content').waitFor({state:'visible'});
   const expected=days==='90'?13:days==='365'?13:Number(days);
   assert.equal(await page.locator('#booking-chart button').count(),expected);
  }
  for(const width of [1440,390,320]) {
   await page.setViewportSize({width,height:1000});
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),`Page overflow at ${width}`);
   assert(await page.locator('#booking-chart span').evaluateAll(spans=>spans.some(s=>s.getBoundingClientRect().height>0)),'Nonblank booking chart');
   await page.screenshot({path:path.join(os.tmpdir(),`admin-reports-${width}.png`),fullPage:true});
  }
  await page.route('**/api/admin/reports*',route=>route.fulfill({status:503,json:{message:'Reports unavailable. Try again.'}}));
  await page.getByRole('button',{name:'Refresh',exact:true}).click();
  await page.getByText('Reports unavailable. Try again.',{exact:true}).waitFor();
  assert(await page.locator('#export-report').isDisabled());
  await page.unroute('**/api/admin/reports*');
  await page.getByRole('button',{name:'Refresh',exact:true}).click();
  await page.locator('#report-content').waitFor({state:'visible'});
  const unsafe='<img src=x onerror="window.unsafeReport=true">';
  await f.db.query('UPDATE providers SET full_name=$1 WHERE id=82',[unsafe]);
  await f.db.query("UPDATE promotion_orders SET plan_name='=SUM(1,2)' WHERE status='paid'");
  await page.getByRole('button',{name:'Refresh',exact:true}).click();
  await page.getByText('1. '+unsafe,{exact:true}).waitFor();
  assert.equal(await page.locator('#top-providers img').count(),0);
  assert.equal(await page.evaluate(()=>window.unsafeReport),undefined);
  const safeDownloadEvent=page.waitForEvent('download');
  await page.locator('#export-report').click();
  const safeDownload=await safeDownloadEvent;
  assert.match(await fs.readFile(await safeDownload.path(),'utf8'),/"'=SUM\(1,2\)"/);
  await f.db.query('DELETE FROM customer_reviews');
  await f.db.query('DELETE FROM customer_bookings');
  await f.db.query('DELETE FROM promotion_orders');
  await page.locator('#refresh-report').click();
  await page.getByText('No activity recorded in this period.',{exact:true}).waitFor();
  assert.match(await page.locator('#report-metrics').innerText(),/Not rated/);
  const anonymous=await browser.newPage();
  await anonymous.goto(f.base+'/pages/admin/reports/reports.html');
  await anonymous.locator('#report-login').waitFor({state:'visible'});
  assert(await anonymous.locator('#report-content').isHidden());
  assert.deepEqual(errors,[]);
  console.log('PASS: admin-only reports, period boundaries, booking-based categories, independent provider rankings, verified-only revenue, trends, zero states, export safety, retry, interactive charts and desktop/mobile layouts.');
 } finally { if(browser) await browser.close(); await f.close(); }
}
main().catch(error=>{console.error(error);process.exitCode=1;});
