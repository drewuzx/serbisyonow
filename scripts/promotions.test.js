'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const { startQrFixture } = require('./provider-qr-test-fixture');
const { issueSession } = require('./account-sessions');
const { planInput } = require('./promotions');

test('promotion plan validation rejects invalid prices, durations and toggles', () => {
 const good = { name:'Boost', description:'Priority',kind:'promotion',duration_days:14,price:'100.50',enabled:true };
 assert.deepEqual(planInput(good), ['Boost','Priority','promotion',14,10050,true]);
 for (const change of [{ price:0 },{ price:'-1' },{ price:'NaN' },{ price:'100.001' },{ price:100001 },{ duration_days:0 },{ duration_days:1.5 },{ enabled:'true' },{ kind:'badge' }]) assert.throws(() => planInput({ ...good,...change }));
 assert.equal(planInput({ ...good,enabled:false,price:0 })[4], 0);
});

test('admin QR purchases verify once, keep payment snapshots, expire, and boost matching search only', async () => {
 const f = await startQrFixture();
 try {
  const admin = (await f.db.query("INSERT INTO admins(username,password_hash) VALUES('promotion-admin','fixture') RETURNING id")).rows[0];
  const adminToken = await issueSession(f.db,'admin',admin.id);
  const adminRequest = (path='',method='GET',body) => f.request('/api/admin/promotions'+path,method,body,adminToken);
  const providerRequest = (path='',method='GET',body,token=f.providerToken) => f.request('/api/provider/81/promotions'+path,method,body,token);
  assert.equal((await f.request('/api/admin/promotions')).status,403);
  assert.equal((await f.request('/api/admin/promotions','GET',undefined,null)).status,401);
  const initial = await adminRequest();
  assert.equal(initial.status,200,JSON.stringify(initial.data));
  assert.equal(initial.data.plans[0].enabled,false);
  assert.equal(initial.data.settings.configured,false);
  assert.equal(initial.data.gateway.channel,'manual','New purchases default to admin-verified QR payments');
  let plan = initial.data.plans[0];
  const body = { name:'14-day Profile Boost',description:'Priority in matching recommended searches.',kind:'promotion',duration_days:14,price:199,enabled:true };
  plan = (await adminRequest('/plans/'+plan.id,'PATCH',body)).data.plan;
  const orderBody = () => ({ plan_id:plan.id,revision:plan.updated_at,request_id:crypto.randomUUID(),accept_terms:true });
  assert.equal((await providerRequest('/orders','POST',orderBody())).status,409,'QR is required before buying');
  assert.equal((await adminRequest('/payment-qr','PUT',f.qrForm('Platform Admin'))).status,200);
  assert.equal((await providerRequest('/orders','POST',{...orderBody(),revision:'old'})).status,409);
  assert.equal((await providerRequest('/orders','POST',orderBody(),f.otherProviderToken)).status,403);
  const attempt = orderBody();
  const created = await providerRequest('/orders','POST',attempt);
  assert.equal(created.status,201,JSON.stringify(created.data));
  const id = created.data.id;
  assert.equal((await providerRequest('/orders','POST',attempt)).data.id,id,'Retries are idempotent');
  assert.equal((await providerRequest('/orders','POST',orderBody())).status,409,'One unfinished order per provider');
  assert.equal((await f.request(`/api/promotion-media/qr/${id}?role=provider`,'GET',undefined,f.otherProviderToken)).status,404);
  assert.equal((await f.request(`/api/promotion-media/qr/${id}?role=provider`,'GET',undefined,f.providerToken)).status,200);
  await adminRequest('/payment-qr','PUT',f.qrForm('Changed Admin'));
  await adminRequest('/plans/'+plan.id,'PATCH',{...body,price:499,duration_days:30});
  let order = (await providerRequest()).data.orders[0];
  assert.equal(order.payment_channel,'manual');
  assert.equal(order.account_name,'Platform Admin');
  assert.equal(order.amount_centavos,19900); assert.equal(order.duration_days,14);
  const receipt = reference => { const form = new FormData(); form.append('reference_number',reference); form.append('receipt',new Blob([f.image],{type:'image/png'}),'receipt.png'); return form; };
  assert.equal((await providerRequest(`/orders/${id}/receipt`,'POST',receipt('PROMO-ONE'))).status,201);
  assert.equal((await providerRequest(`/orders/${id}/cancel`,'PATCH')).status,409);
  order = (await providerRequest()).data.orders[0];
  assert.equal(order.status,'awaiting_verification');
  assert.equal((await providerRequest()).data.current_boost,null,'Uploading a receipt does not activate the promotion');
  const review = { decision:'verify',receipt_id:order.receipt_id,payment_received:true };
  assert.equal((await adminRequest(`/orders/${id}/review`,'PATCH',{...review,payment_received:false})).status,400);
  assert.equal((await adminRequest(`/orders/${id}/review`,'PATCH',{...review,decision:'reject',notes:''})).status,400);
  assert.equal((await adminRequest(`/orders/${id}/review`,'PATCH',{...review,decision:'reject',notes:'Reference is not visible.'})).status,200);
  assert.equal((await providerRequest(`/orders/${id}/receipt`,'POST',receipt('PROMO-ONE'))).status,201,'Rejected receipt can be corrected without another transfer');
  order = (await providerRequest()).data.orders[0];
  assert.equal((await adminRequest(`/orders/${id}/review`,'PATCH',review)).status,409,'Old receipt cannot be approved');
  const responses = await Promise.all([adminRequest(`/orders/${id}/review`,'PATCH',{...review,receipt_id:order.receipt_id}),adminRequest(`/orders/${id}/review`,'PATCH',{...review,receipt_id:order.receipt_id})]);
  assert.deepEqual(responses.map(r=>r.status).sort(),[200,409]);
  const revenue = await adminRequest();
  assert.equal(Number(revenue.data.metrics.revenue_centavos),19900);
  assert.equal(revenue.data.metrics.active_providers,1);
  order = (await providerRequest()).data.orders[0];
  assert.equal(order.display_status,'active');
  assert.equal((await providerRequest('?status=cancelled&page=2')).data.current_boost.id,order.id);
  assert.equal((new Date(order.expires_at)-new Date(order.starts_at))/86400000,14);
  const recommended = await f.request('/api/providers/search?category=Cleaning');
  assert.equal(recommended.status,200,JSON.stringify(recommended.data));
  assert.equal(recommended.data.providers[0].id,81); assert.equal(recommended.data.providers[0].promoted,true);
  assert.equal((await f.request('/api/providers/search?category=Nail%20Care')).data.providers.some(p=>p.id===81),false);
  plan = (await adminRequest()).data.plans.find(p=>p.id===plan.id);
  const next = (await providerRequest('/orders','POST',orderBody())).data.id;
  assert.equal((await providerRequest(`/orders/${next}/receipt`,'POST',receipt('PROMO-ONE'))).status,409,'References cannot be reused by another order');
  assert.equal((await providerRequest(`/orders/${next}/receipt`,'POST',receipt('PROMO-TWO'))).status,201);
  const nextOrder = (await providerRequest()).data.orders.find(o=>o.id===next);
  await adminRequest(`/orders/${next}/review`,'PATCH',{decision:'verify',receipt_id:nextOrder.receipt_id,payment_received:true});
  const scheduled = (await providerRequest()).data.orders.find(o=>o.id===next);
  assert.equal(scheduled.display_status,'scheduled'); assert.equal(scheduled.starts_at,order.expires_at);
  await f.db.query("UPDATE promotion_orders SET starts_at=NOW()-INTERVAL '20 days',expires_at=NOW()-INTERVAL '1 day' WHERE provider_id=81");
  assert.equal((await providerRequest()).data.orders[0].display_status,'expired');
  assert.equal((await providerRequest()).data.current_boost,null);
  assert.equal((await f.request('/api/providers/search')).data.providers.find(p=>p.id===81).promoted,false);
  assert.equal((await adminRequest()).data.metrics.active_providers,0);
  assert.equal(Number((await adminRequest()).data.metrics.revenue_centavos),69800,'Expiry does not erase received revenue');
  await f.createBooking({status:'completed',deposit_status:'paid',confirmed_price:1000,deposit_amount:300,balance_due:700});
  const serviceLedger = (await adminRequest()).data;
  assert.equal(Number(serviceLedger.metrics.revenue_centavos),69800,'Provider transfers must not inflate platform revenue');
  assert.equal(Number(serviceLedger.earnings[0].verified_downpayments),300);
  assert.equal(Number(serviceLedger.earnings[0].unverified_balances),700);
  await f.db.query(`INSERT INTO promotion_orders(provider_id,plan_id,request_id,plan_name,description,duration_days,amount_centavos,status,wallet,account_name,account_number,qr_content,qr_mime)
   SELECT provider_id,plan_id,gen_random_uuid(),plan_name,description,duration_days,amount_centavos,'cancelled',wallet,account_name,account_number,qr_content,qr_mime
   FROM promotion_orders CROSS JOIN generate_series(1,28) WHERE id=$1`,[id]);
  assert.equal((await adminRequest()).data.order_count,30);
  assert.equal((await adminRequest()).data.orders.length,25);
  assert.equal((await adminRequest('?page=2')).data.orders.length,5);
  assert.equal((await adminRequest('?status=expired')).data.order_count,2);
  assert.equal((await adminRequest('?status=awaiting_verification')).data.order_count,0);
  assert.equal((await adminRequest('?page=-1')).status,400);
  assert.equal((await adminRequest('?status=constructor')).status,400);
 } finally { await f.close(); }
});
